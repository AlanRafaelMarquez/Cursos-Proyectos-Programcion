package Entrada_de_datos;

public class Operadores_aritmeticos_asignacion {
    public static void main (String[] args){
        int numero = 10;
        //Combinacion de operadores
        numero += 5;
        numero -= 5;
        numero *= 5;
        numero /= 5;
        numero %= 5;

        System.out.println(numero);
    }
}
